/** Minimal JSONC reader (VS Code language-configuration files allow comments and trailing commas). */
export function parseJsonc<T = unknown>(src: string): T {
  let out = '';
  let inStr = false;
  for (let i = 0; i < src.length; i++) {
    const c = src[i];
    if (inStr) {
      out += c;
      if (c === '\\') out += src[++i];
      else if (c === '"') inStr = false;
      continue;
    }
    if (c === '"') { inStr = true; out += c; continue; }
    if (c === '/' && src[i + 1] === '/') { while (i < src.length && src[i] !== '\n') i++; out += '\n'; continue; }
    if (c === '/' && src[i + 1] === '*') { i += 2; while (i < src.length && !(src[i] === '*' && src[i + 1] === '/')) i++; i++; continue; }
    out += c;
  }
  // trailing commas (outside strings is a safe enough assumption for these configs)
  return JSON.parse(out.replace(/,(\s*[}\]])/g, '$1')) as T;
}
