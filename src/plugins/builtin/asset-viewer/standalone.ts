/**
 * DDS / 텍스처 뷰어 플러그인 독립 실행형 스크립트
 * 외부 플러그인 디렉터리에 내보내거나 단독 ES 모듈로 실행할 때 사용되는 예제 코드입니다.
 */
export const standaloneScript = [
  '// DDS / 텍스처 뷰어 플러그인 (Asset Viewer Plugin)',
  'export default {',
  '  activate(context) {',
  '    context.editor.registerCustomViewer({',
  "      id: 'asset-viewer',",
  "      name: 'DDS / 텍스처 뷰어',",
  "      extensions: ['dds', 'png', 'jpg', 'jpeg', 'bmp', 'webp', 'gif'],",
  '      render(container, file) {',
  "        container.style.cssText = 'display:flex;align-items:center;justify-content:center;height:100%;color:#ccc;flex-direction:column;gap:12px;';",
  "        const title = document.createElement('div');",
  "        title.textContent = '에셋 뷰어: ' + file.name;",
  "        title.style.fontWeight = 'bold';",
  '        container.appendChild(title);',
  '',
  "        if (file.name.toLowerCase().endsWith('.dds')) {",
  "          const info = document.createElement('div');",
  "          info.textContent = 'DDS 바이너리 (' + file.bytes.byteLength + ' 바이트) - 내장 캔버스 뷰어로 렌더링됩니다.';",
  '          container.appendChild(info);',
  '        } else {',
  '          const blob = new Blob([file.bytes]);',
  '          const url = URL.createObjectURL(blob);',
  "          const img = document.createElement('img');",
  '          img.src = url;',
  "          img.style.maxWidth = '90%';",
  "          img.style.maxHeight = '80%';",
  '          container.appendChild(img);',
  '          return () => URL.revokeObjectURL(url);',
  '        }',
  '      },',
  '    });',
  '  },',
  '  deactivate() {},',
  '};',
].join('\n');
